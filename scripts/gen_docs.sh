#!/usr/bin/env bash
# Generate the API reference (docs/api/*.md) from the shdoc comments.
# Requires shdoc (https://github.com/reconquest/shdoc) in PATH, or SHDOC=/path/to/shdoc.
set -eu
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SHDOC="${SHDOC:-shdoc}"
command -v "$SHDOC" >/dev/null 2>&1 || [ -x "$SHDOC" ] || {
	echo "shdoc not found. Install it (see docs/CONVENTIONS.md) or set SHDOC=/path/to/shdoc" >&2
	exit 1
}

out="$ROOT/docs/api"
rm -rf "$out"
mkdir -p "$out"
index="$out/README.md"
{
	echo "# API reference"
	echo
	echo "Generated by \`make docs\` from the shdoc comments in \`src/\`. Do not edit by hand."
	echo
} >"$index"

for group in core dependency lib skill lang devops shield bot; do
	echo "## $group" >>"$index"
	echo >>"$index"
	for f in "$ROOT"/src/$group/*.sh; do
		name="$(basename "$f" .sh)"
		target="$out/$group-$name.md"
		"$SHDOC" <"$f" >"$target"
		count="$(grep -c '^### ' "$target" || true)"
		echo "- [\`$group/$name.sh\`]($group-$name.md) ($count functions)" >>"$index"
	done
	echo >>"$index"
done
echo "Wrote $(ls "$out" | wc -l | tr -d ' ') files to docs/api/"
