#!/usr/bin/env bash
# @file loader/lazy.sh
# @brief Lazy loading of the library: cache of one-line stubs, generated on first start.
# @description
#   Sourced by src/shell.sh on every start (it only defines functions). Sourcing every module on
#   each start costs parse time proportional to the library (about 2.5 MB); the cache replaces
#   the functions of every "pure" module by stubs, and the first call into a module loads it.
#   SHELL_LAZY=0 or SHELL_DEBUG=1 disables the cache and loads everything eagerly.
#   The cache lives in `<install dir>/.cache/lazy.sh`: an upgrade replaces the install directory,
#   so a new version never sees an old cache, and uninstall removes it with the directory.

# @description Tell whether the lazy cache is newer than every module, group directory, shell.sh and this file.
#   `-nt` is a builtin, so the check forks nothing. A directory changes when a module is added or removed.
# @internal
# @arg $1 string Cache file.
# @exitcode 0 The cache is fresh.
# @exitcode 1 The cache is missing or stale.
# @example
#   _shell::lazy::fresh "$SHELL_DIR/.cache/lazy.sh"
#
_shell::lazy::fresh() {
	local cache="$1" entry group
	[ -r "$cache" ] || return 1
	if [ -n "${ZSH_VERSION-}" ]; then
		setopt local_options null_glob
	fi
	[ "$SHELL_SRC_DIR/shell.sh" -nt "$cache" ] && return 1
	[ "$SHELL_SRC_DIR/loader/lazy.sh" -nt "$cache" ] && return 1
	for group in "${SHELL_MODULE_GROUPS[@]}"; do
		[ "$SHELL_SRC_DIR/$group" -nt "$cache" ] && return 1
		for entry in "$SHELL_SRC_DIR/$group"/*.sh; do
			[ "$entry" -nt "$cache" ] && return 1
		done
	done
	return 0
}

# @description Write the lazy cache for the current SHELL_SRC_DIR.
#   Sourcing every module on each shell start costs parse time proportional to the library
#   (about 2.5 MB). The cache replaces every function of a "pure" module (a file that only
#   defines functions) by a one-line stub; the first call of any function of that module
#   sources the real file and re-runs the call (see _shell::lazy::run).
#
#   Files with top-level statements (constants, aliases, option defaults, widgets) are never
#   lazy: they become `_shell::lazy::eager` lines and run at load, exactly as before. A
#   function defined by two files forces both files eager, so "last definition wins" keeps its
#   meaning. Output goes to a temporary file moved into place atomically.
#
#   Contributor rule: no command substitutions, external commands, file reads or network at
#   the top level of a module. A module that breaks it silently stays eager.
# @internal
# @arg $1 string Destination cache file.
# @exitcode 0 The cache was written.
# @exitcode 1 The cache could not be written (the caller falls back to eager loading).
# @example
#   _shell::lazy::build "${SHELL_SRC_DIR%/*}/.cache/lazy.sh"
#
_shell::lazy::build() {
	local dest="${1-}" dir tmp group file
	local -a files=()
	[ -n "$dest" ] || return 1
	dir="${dest%/*}"
	mkdir -p "$dir" 2>/dev/null || return 1
	tmp="$(mktemp "$dir/.lazy.XXXXXX" 2>/dev/null)" || return 1

	if [ -n "${ZSH_VERSION-}" ]; then
		setopt local_options null_glob
	fi
	for group in "${SHELL_MODULE_GROUPS[@]}"; do
		for file in "$SHELL_SRC_DIR/$group"/*.sh; do
			[ -f "$file" ] && files+=("$file")
		done
	done

	{
		printf '%s\n' '# Generated by _shell::lazy::build. Do not edit. Safe to delete.'
		printf '%s\n' "_SHELL_LAZY_DONE='|'"
		# Captured at load: a later change of SHELL_SRC_DIR must not redirect the stubs.
		printf '%s\n' '_SHELL_LAZY_ROOT="$SHELL_SRC_DIR"'
		awk -v root="$SHELL_SRC_DIR/" '
			FNR == 1 { n++; rel[n] = substr(FILENAME, length(root) + 1); infn = 0; hd = ""; stubs[n] = ""; names[n] = ""; code[n] = 0 }
			{
				line = $0
				if (infn) {
					# Inside a heredoc nothing counts, not even a "}" in column 0.
					if (hd != "") {
						cmp = line
						if (hddash) sub(/^\t+/, "", cmp)
						if (cmp == hd) hd = ""
						next
					}
					if (line ~ /^}[ \t]*$/) { infn = 0; next }
					if (match(line, /<<-?[ \t]*[\042\047\\]?[A-Za-z_][A-Za-z0-9_]*/) && substr(line, RSTART, 3) != "<<<") {
						tok = substr(line, RSTART, RLENGTH)
						hddash = (tok ~ /^<<-/)
						sub(/^<<-?[ \t]*[\042\047\\]?/, "", tok)
						hd = tok
					}
					next
				}
				if (line ~ /^[ \t]*$/ || line ~ /^[ \t]*#/) next
				if (match(line, /^(function[ \t]+)?_?shell::[A-Za-z0-9_:]+[ \t]*\(\)[ \t]*\{[ \t]*$/)) {
					name = line
					sub(/^function[ \t]+/, "", name)
					sub(/[ \t]*\(\).*$/, "", name)
					if (name in owner) { code[n] = 1; code[owner[name]] = 1 }
					else owner[name] = n
					stubs[n] = stubs[n] name "() { _shell::lazy::run " rel[n] " " name " \"$@\"; }\n"
					names[n] = (names[n] == "" ? name : names[n] " " name)
					infn = 1
					next
				}
				code[n] = 1
			}
			END {
				map = ""
				for (i = 1; i <= n; i++) {
					if (code[i] || stubs[i] == "") printf "_shell::lazy::eager %s\n", rel[i]
					else {
						printf "%s", stubs[i]
						map = map "\n" rel[i] " " names[i]
					}
				}
				# One line per lazy module: its path, then every function it defines.
				printf "_SHELL_LAZY_MAP=\047%s\n\047\n", map
			}' "${files[@]}"
	} >"$tmp" 2>/dev/null || {
		rm -f "$tmp"
		return 1
	}
	mv -f "$tmp" "$dest" 2>/dev/null || {
		rm -f "$tmp"
		return 1
	}
	return 0
}

# @description Source one module listed in the lazy cache as eager (it has top-level code).
# @internal
# @arg $1 string Module path relative to SHELL_SRC_DIR.
# @exitcode 0 Always (a failure is reported on stderr and counted in SHELL_LOAD_ERRORS).
# @example
#   _shell::lazy::eager constant/system.sh
#
_shell::lazy::eager() {
	# shellcheck source=/dev/null
	source "$_SHELL_LAZY_ROOT/$1" || {
		printf 'shell: failed to load %s\n' "$_SHELL_LAZY_ROOT/$1" >&2
		SHELL_LOAD_ERRORS=$((SHELL_LOAD_ERRORS + 1))
	}
	return 0
}

# @description Run a function of a lazily loaded module: source the module, then call the function.
#   Overrides survive: a function of the module that was redefined (by a user or a test) before the
#   module loaded is saved and put back after it, exactly as if the module had been loaded at start.
#   Uses no external command except `rm`, and only when an override exists. Costs one subshell on
#   the FIRST call into each module in bash, never at shell start.
# @internal
# @arg $1 string Module path relative to SHELL_SRC_DIR.
# @arg $2 string Function to call once the module is loaded.
# @arg $@ string Arguments of that call, passed through unchanged.
# @exitcode 127 The module does not define the function.
# @exitcode 1 The module failed to load.
# @example
#   _shell::lazy::run lib/goto.sh shell::goto "$@"
#
_shell::lazy::run() {
	local _lz_rel="$1" _lz_fn="$2" _lz_cache="${_SHELL_LAZY_ROOT%/*}/.cache/lazy.sh" _lz_names _lz_keep="" _lz_n _lz_l _lz_f _lz_info _lz_tmp
	shift 2
	case "$_SHELL_LAZY_DONE" in
	*"|$_lz_rel|"*)
		printf 'shell: %s is not defined by %s\n' "$_lz_fn" "$_lz_rel" >&2
		return 127
		;;
	esac
	_SHELL_LAZY_DONE="${_SHELL_LAZY_DONE}${_lz_rel}|"

	# Which functions of this module are no longer our stubs? A stub is defined in the cache file.
	_lz_names="${_SHELL_LAZY_MAP#*$'\n'"$_lz_rel "}"
	_lz_names="${_lz_names%%$'\n'*}"
	if [ -n "${ZSH_VERSION-}" ]; then
		setopt local_options sh_word_split
		# functions_source (zsh/parameter) names the file a function came from; skip the check when
		# this zsh does not provide it (the stub being called must have a source).
		if [ -n "${functions_source[$_lz_fn]-}" ]; then
			for _lz_n in $_lz_names; do
				[ "${functions_source[$_lz_n]-}" = "$_lz_cache" ] || _lz_keep="$_lz_keep $_lz_n"
			done
		fi
	else
		_lz_info="$(
			shopt -s extdebug
			# shellcheck disable=SC2086
			declare -F $_lz_names
		)"
		while read -r _lz_n _lz_l _lz_f; do
			[ "$_lz_f" = "$_lz_cache" ] || _lz_keep="$_lz_keep $_lz_n"
		done <<LZ_EOF
$_lz_info
LZ_EOF
	fi
	if [ -n "$_lz_keep" ]; then
		_lz_tmp="${_lz_cache%/*}/ovr.$$"
		# shellcheck disable=SC2086
		typeset -f $_lz_keep >"$_lz_tmp" 2>/dev/null || _lz_keep=""
	fi

	# shellcheck source=/dev/null
	if ! source "$_SHELL_LAZY_ROOT/$_lz_rel"; then
		printf 'shell: failed to load %s\n' "$_SHELL_LAZY_ROOT/$_lz_rel" >&2
		[ -n "$_lz_keep" ] && rm -f "$_lz_tmp"
		return 1
	fi
	if [ -n "$_lz_keep" ]; then
		# shellcheck source=/dev/null
		source "$_lz_tmp"
		rm -f "$_lz_tmp"
	fi
	"$_lz_fn" "$@"
}
